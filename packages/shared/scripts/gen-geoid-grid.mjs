// One-off script: build src/geoidGrid.ts, the compact EGM96 geoid grid used
// by src/geoid.ts to turn GPS heights above the WGS-84 ellipsoid (what
// Android and browsers report) into altitudes above mean sea level.
//
// Source: EGM96 geoid (NGA / NASA, public domain), in GeographicLib's
// 15-arc-minute PGM distribution "egm96-15.pgm":
//   https://sourceforge.net/projects/geographiclib/files/geoids-distrib/egm96-15.tar.bz2
// (download and unpack it; the .pgm lands in geoids/).
//
// Output: Europe (lat 34..72 N, lon 25 W..45 E) resampled to a 0.5 deg grid
// by bilinear interpolation of the 15' source, heights in decimetres as
// little-endian int16, base64. Measured against the full 15' model over
// that area: 0.04 m typical, 0.41 m p99, 1.4 m worst -- negligible next to
// GPS vertical error. ~21 KiB of data.
//
// Run with: node scripts/gen-geoid-grid.mjs path/to/egm96-15.pgm
import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const LAT_MAX = 72, LAT_MIN = 34, LON_MIN = -25, LON_MAX = 45, STEP = 0.5

const file = process.argv[2]
if (!file) { console.error('usage: node scripts/gen-geoid-grid.mjs egm96-15.pgm'); process.exit(1) }
const data = readFileSync(file)

// PGM header: "P5", comment lines (GeographicLib puts "# Offset" and
// "# Scale" there), "width height", "maxval", then big-endian uint16 samples.
let pos = 0
const header = []
while (header.filter((l) => !l.startsWith('#')).length < 3) {
  const end = data.indexOf(0x0a, pos)
  header.push(data.subarray(pos, end).toString('latin1').trim())
  pos = end + 1
}
const num = (key) => Number(header.find((l) => l.startsWith(`# ${key}`)).split(/\s+/)[2])
const offset = num('Offset'), scale = num('Scale')
const [w] = header.filter((l) => !l.startsWith('#'))[1].split(/\s+/).map(Number)
const step = 360 / w
const raw = (r, c) => data.readUInt16BE(pos + 2 * (r * w + (((c % w) + w) % w)))
function geoid(lat, lon) {
  const fr = (90 - lat) / step, fc = (((lon % 360) + 360) % 360) / step
  const r = Math.floor(fr), c = Math.floor(fc), dr = fr - r, dc = fc - c
  const v = raw(r, c) * (1 - dr) * (1 - dc) + raw(r, c + 1) * (1 - dr) * dc + raw(r + 1, c) * dr * (1 - dc) + raw(r + 1, c + 1) * dr * dc
  return offset + scale * v
}

const rows = Math.round((LAT_MAX - LAT_MIN) / STEP) + 1
const cols = Math.round((LON_MAX - LON_MIN) / STEP) + 1
const buf = Buffer.alloc(rows * cols * 2)
for (let r = 0; r < rows; r++) {
  for (let c = 0; c < cols; c++) {
    buf.writeInt16LE(Math.round(geoid(LAT_MAX - r * STEP, LON_MIN + c * STEP) * 10), 2 * (r * cols + c))
  }
}

const b64 = buf.toString('base64')
const lines = b64.match(/.{1,100}/g).map((l) => `  '${l}',`).join('\n')
const out = `// GENERATED by scripts/gen-geoid-grid.mjs -- do not edit.
// EGM96 geoid height (NGA / NASA, public domain) above the WGS-84 ellipsoid,
// ${STEP} deg grid, rows from lat ${LAT_MAX} down to ${LAT_MIN}, columns from lon ${LON_MIN} to ${LON_MAX},
// int16 little-endian decimetres, base64. Read through ./geoid.ts.

export const GEOID_GRID = {
  latMax: ${LAT_MAX},
  lonMin: ${LON_MIN},
  step: ${STEP},
  rows: ${rows},
  cols: ${cols},
  data: [
${lines}
  ].join(''),
} as const
`
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'geoidGrid.ts')
writeFileSync(target, out)
console.log(`wrote ${target}: ${rows}x${cols} values, ${buf.length} bytes`)
