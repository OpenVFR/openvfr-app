#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-NOTICES.md: every npm package that ships in the web
 * bundle and the native apps (runtime dependencies only -- no build/test
 * tooling, no API server), with its licence and the package's own licence /
 * notice text, so the licences' "keep the copyright notice" duty is met.
 *
 * It is the single source: openvfr.org/licences renders this file, and both
 * apps link there from Settings -> About.
 *
 *   node scripts/third-party-notices.mjs           write THIRD-PARTY-NOTICES.md
 *   node scripts/third-party-notices.mjs --check   exit 1 if the file is stale
 *                                                  or a package breaks OSS-POLICY.md
 *
 * Needs `pnpm install` first (reads the packages' files from node_modules).
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'THIRD-PARTY-NOTICES.md')
const check = process.argv.includes('--check')

// Workspace packages whose runtime dependencies ship to users.
const SHIPPED = ['web', 'native']

// OSS-POLICY.md section 3: strong copyleft is not allowed. An "A OR B"
// expression is fine when one side is permissive (we use that side).
const FORBIDDEN = /\b(A?GPL|SSPL)/i
const forbidden = (lic) => {
  const options = lic.replace(/[()]/g, '').split(/\s+OR\s+/i)
  return options.every((o) => FORBIDDEN.test(o))
}

const pkgs = new Map() // "name@version" -> { name, version, license, homepage, path, apps:Set }
for (const app of SHIPPED) {
  const json = execFileSync('pnpm', ['licenses', 'list', '--prod', '--filter', app, '--json'], {
    cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024,
  })
  for (const [license, list] of Object.entries(JSON.parse(json))) {
    for (const p of list) {
      p.versions.forEach((version, i) => {
        const key = `${p.name}@${version}`
        const e = pkgs.get(key) ?? { name: p.name, version, license, homepage: p.homepage ?? '', path: p.paths[i] ?? p.paths[0], apps: new Set() }
        e.apps.add(app)
        pkgs.set(key, e)
      })
    }
  }
}

const bad = [...pkgs.values()].filter((p) => forbidden(p.license))
if (bad.length) {
  console.error('Packages with a licence OSS-POLICY.md does not allow:')
  for (const p of bad) console.error(`  ${p.name}@${p.version}  ${p.license}`)
  process.exit(1)
}

/** The package's own licence / notice files (LICENSE*, COPYING*, NOTICE*), trimmed. */
function legalText(path) {
  if (!path || !existsSync(path)) return ''
  const files = readdirSync(path).filter((f) => /^(licen[cs]e|copying|notice)(\.|$|-)/i.test(f)).sort()
  return files
    .map((f) => { try { return readFileSync(join(path, f), 'utf8').replace(/\r\n/g, '\n').trim() } catch { return '' } })
    .filter(Boolean)
    .join('\n\n')
}

// One block of text per distinct licence text, listing the packages it covers.
const byText = new Map() // normalised text -> { text, names:Set }
const noText = []
for (const p of pkgs.values()) {
  const text = legalText(p.path)
  if (!text) { noText.push(p); continue }
  const key = text.replace(/\s+/g, ' ')
  const e = byText.get(key) ?? { text, names: new Set() }
  e.names.add(`${p.name}@${p.version}`)
  byText.set(key, e)
}

const rows = [...pkgs.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
const counts = {}
for (const p of rows) counts[p.license] = (counts[p.license] ?? 0) + 1

const md = []
md.push('# Third-party notices', '')
md.push('OpenVFR is MIT-licensed ([LICENSE](./LICENSE)). The web app and the native apps include the open-source packages below.')
md.push('Each is used under its own licence; the notices those licences require follow the list.')
md.push('Map, aviation, weather and traffic *data* sources are credited separately (see README, "Data & attribution").', '')
md.push('Generated by `scripts/third-party-notices.mjs` from the production dependencies of the web and native apps. Do not edit by hand.', '')
md.push(`## Packages (${rows.length})`, '')
md.push('Licences: ' + Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(', '), '')
md.push('| Package | Version | Licence | Used in |', '|---|---|---|---|')
for (const p of rows) md.push(`| ${p.name} | ${p.version} | ${p.license} | ${[...p.apps].sort().join(', ')} |`)
md.push('', '## Licence texts', '')
const blocks = [...byText.values()].sort((a, b) => [...a.names].sort()[0].localeCompare([...b.names].sort()[0]))
for (const b of blocks) {
  md.push('### ' + [...b.names].sort().join(', '), '', '```text', b.text, '```', '')
}
if (noText.length) {
  md.push('### Packages that ship no licence file', '')
  md.push('Used under the licence declared in their `package.json`:', '')
  for (const p of noText.sort((a, b) => a.name.localeCompare(b.name))) md.push(`- ${p.name}@${p.version}: ${p.license}${p.homepage ? ` (${p.homepage})` : ''}`)
  md.push('')
}
const out = md.join('\n')

if (check) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (cur !== out) {
    console.error('THIRD-PARTY-NOTICES.md is out of date. Run: node scripts/third-party-notices.mjs')
    process.exit(1)
  }
  console.log('THIRD-PARTY-NOTICES.md is up to date.')
} else {
  writeFileSync(OUT, out)
  console.log(`Wrote ${OUT}: ${rows.length} packages, ${blocks.length} licence texts, ${noText.length} without a licence file.`)
}
